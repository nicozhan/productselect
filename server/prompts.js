// server/prompts.js
// 构建发给 InfiniSynapse 的分析提示词：围绕「无人零售 / 自动售货柜选品」的 12 个维度，
// 并要求返回指定结构的报告 + JSON。
export function buildPrompt(inputs = {}) {
  const {
    scenarioName, location, city, deviceId, weather = {}, event, holiday,
    demographics = {}, salesData, inventoryNotes, tomorrow, businessHours, focus
  } = inputs;

  const w = weather || {};
  const d = demographics || {};

  // 时间锚点：让 AI 有「当前月份/季节」可据以推断天气与节令选品
  const now = new Date();
  const m = now.getMonth() + 1;
  const season = (m >= 3 && m <= 5) ? '春季' : (m >= 6 && m <= 8) ? '夏季' : (m >= 9 && m <= 11) ? '秋季' : '冬季';
  const place = city || location || '当地';

  // 天气：用户通常不掌握，交由 AI 联网查询或按月份/城市推断
  const hasWeather = w && (w.temp != null || w.rain != null || w.humidity != null);
  const weatherLine = hasWeather
    ? `温度 ${w.temp ?? '未知'}℃、降雨 ${w.rain ?? '未知'}、湿度 ${w.humidity ?? '未知'}%`
    : `（用户未提供，请联网查询「${place}」当前天气，或依据当前为 ${m} 月（${season}）推断典型温度/降雨/湿度，并分析其对选品的影响）`;

  // 用户画像：依场景类型由 AI 推断
  const hasDemo = d && (d.genderRatio || d.ageRange);
  const demoLine = hasDemo
    ? `性别比 ${d.genderRatio || '未知'}、年龄段 ${d.ageRange || '未知'}`
    : `（用户未提供，请依据场景类型「${scenarioName || '自定义场景'}」（写字楼/高校/工厂/商场/酒吧/医院/景区等）推断典型性别比与年龄段）`;

  const salesBlock = (salesData && salesData.trim())
    ? salesData.trim()
    : '(用户未提供历史销售明细，请基于场景类型与零售常识进行合理估算，并在报告中用「估算」字样明确标注)';

  const tomorrowBlock = tomorrow
    ? `明日环境预测（用于 AI Tomorrow 模块）：\n- 天气：${tomorrow.weather || '未知'}\n- 附近活动：${tomorrow.event || '无'}\n- 是否节假日：${tomorrow.holiday ? '是' : '否'}`
    : '(若用户未提供明日预测，请基于今日环境做合理推断，并标注为推断)';

  return `你是「AI 选品大脑（AI Merchandising Agent）」——一个专注**无人零售 / 自动售货柜选品（Assortment）与运营决策**的引擎。

# 你的核心任务
自动售货柜的货道数量有限（通常 30-60 条），你的目标不是出一份泛泛的报表，而是回答一个**动作问题**：
**这个周期，在有限的货道里，应该上架 / 淘汰哪些 SKU、如何定价、如何排布货道、何时补货？**
请像一个管着几百台柜子的资深自动售货运营总监一样思考，给出的每一句话都要可被执行。

# 输入数据
- 设备ID：${deviceId || '未提供'}
- 场景名称：${scenarioName || '自定义场景'}
- 位置 / 城市：${location || '未知'}${city ? ' / ' + city : ''}
- 当前时间：${m} 月（${season}）
- 天气：${weatherLine}
- 附近活动：${event || '无'}
- 是否节假日：${holiday ? '是' : '否'}
- 用户画像：${demoLine}
- 营业时段：${businessHours && businessHours.length ? businessHours.join('、') : '（用户未指定，请按场景类型推断典型高峰时段）'}
- 库存 / 保质期备注：${inventoryNotes || '无'}
- 分析重点（该场景运营方最关心的维度）：${(focus && focus.length) ? focus.join('；') : '（无特别要求）'}

# 历史销售数据
${salesBlock}

${tomorrowBlock}

# 分析要求（请围绕「选品」覆盖以下 12 个维度，按对选品决策的重要性排序）
1. **单品产出与坪效**：每个 SKU / 每条货道的营收贡献、销量、毛利，识别高产出品与占道低效品（占着货道却不卖）。
2. **毛利结构与价格带**：低单价引流品、中价主力利润品、高价溢价品的覆盖是否合理；是否存在价格带空缺。
3. **周转率与售罄率**：快周转畅销品 vs 慢周转滞销品，决定哪些该加量、哪些该淘汰。
4. **缺货与补货可靠性**：哪些 SKU 频繁缺货丢单；补货频次是否匹配真实销量节奏。
5. **临期与损耗**：短保商品（乳品/鲜食/面包）的损耗风险，是否应减少铺货或缩短补货周期。
6. **时段 × 品类匹配**：早 / 午 / 晚 / 夜各时段主力品类（如早晨咖啡+早餐、午后饮料+零食、夜间酒水+宵夜），货道排布是否匹配。
7. **天气联动**：高温→冷饮/冰品/电解质水；低温→热饮/关东煮；雨天→室内零食——**由你（AI）联网查询或按月份城市推断**，用户通常不掌握。
8. **场景适配度**：依据场景类型（写字楼/高校/工厂/商场/酒吧/医院/景区）判断品类契合度，给出增/减品类建议。
9. **商品关联购买（Market Basket）**：2-4 组强搭配（如 咖啡+奶、功能饮料+坚果）及交叉销售提升空间。
10. **活动 / 节假日联动**：附近活动与节假日带来的需求峰值，对应选品与备货调整。
11. **竞品与便利溢价**：相比周边便利店，你的 24h / 就近优势能支撑的溢价空间与差异化选品（不要只比价格）。
12. **新品引入与汰换动作**：本周期建议新增 / 淘汰的 SKU 及理由——这是「选品」的真正落点。

请特别针对上述「分析重点」逐条展开，给出可执行的针对性建议，而不是泛泛而谈。

所有数据已在上方提供，请直接分析，**不要请求上传文件**。请像一个资深自动售货运营总监一样，给出可执行的选品动作，而不是堆砌报表。

# 输出格式（必须包含以下部分，全部使用中文）

## 一句话决策
用一段话给出：明天该主推什么、备多少、放哪个货道、为什么——并点出 1-2 个具体的选品动作（新增 / 淘汰 / 调价）。

## AI 场景识别
列出 500m 内 POI 类型、工作日 / 周末人流估算、客群画像，以及建议增加 / 减少的品类。

## AI 商品评分
对 5-10 个核心 SKU 逐项打分（0-100）。子维度至少包含：**销量贡献、毛利贡献、周转/售罄、缺货风险、关联带动、场景/时段适配**。给出综合评分与动作建议（如「加量 20%」/「淘汰」/「提价 1 元」/「移到黄金货道」）。请用 Markdown 表格呈现。

## 商品关联销售
给出 2-4 组搭配购买（例如 咖啡+奶 68%），并给出交叉销售建议与预计销量提升百分比。

## AI Tomorrow
基于明日环境预测，列出应增加 / 不补的商品及预计销量变化。

## 选品动作清单
用清单（bullet）给出本周期明确可执行动作：新增 SKU（品名 + 目标货道）、淘汰 SKU、提价 / 降价、货道重排。每条一句话说明理由。

## 完整分析报告
展开上述各维度的详细推理、数据依据与风险点。

# 输出与保存要求
1. 请严格使用上述「## 一句话决策 / ## AI 场景识别 / ## AI 商品评分 / ## 商品关联销售 / ## AI Tomorrow / ## 选品动作清单 / ## 完整分析报告」共七个标题，不要改名，便于系统结构化读取。
2. 请将以上完整报告（含全部章节）保存为一个 Markdown 文件，文件名建议为「{场景名}_AI选品分析报告.md」。
3. （可选）你也可以在报告末尾附一个 \`\`\`json 代码块给出机器可读摘要，但不是必须。

所有数据已在上方提供，请直接分析，**不要请求上传文件**。请像一个资深自动售货运营总监一样，给出可执行的选品动作，而不是堆砌报表。
`;
}
